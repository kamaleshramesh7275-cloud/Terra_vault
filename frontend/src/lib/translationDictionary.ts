/**
 * Translate a single word, phrase, or sentence to the target language
 */
export function translatePhrase(text: string, targetLang: string): string {
  if (!text || targetLang === "en") return text;
  const trimmed = text.trim();

  // 1. Direct dictionary match
  if (DICTIONARY[trimmed] && DICTIONARY[trimmed][targetLang]) {
    return DICTIONARY[trimmed][targetLang];
  }

  // 2. Regex phrase match
  for (const rule of PHRASE_RULES) {
    if (rule.match.test(text) && rule.replace[targetLang]) {
      return text.replace(rule.match, rule.replace[targetLang]);
    }
  }

  // 3. Case-insensitive key match
  const lower = trimmed.toLowerCase();
  for (const [key, map] of Object.entries(DICTIONARY)) {
    if (key.toLowerCase() === lower && map[targetLang]) {
      return map[targetLang];
    }
  }

  return text;
}
